function setDeep(obj, path, value) {
  const parts = path.split('.')
  let cur = obj
  for (let i = 0; i < parts.length - 1; i++) {
    if (typeof cur[parts[i]] !== 'object' || cur[parts[i]] === null) cur[parts[i]] = {}
    cur = cur[parts[i]]
  }
  cur[parts[parts.length - 1]] = value
}

function flatten(obj, prefix = '', out = new Set()) {
  for (const [k, v] of Object.entries(obj)) {
    const key = prefix ? `${prefix}.${k}` : k
    if (v && typeof v === 'object') flatten(v, key, out)
    else out.add(key)
  }
  return out
}

/** 记录本轮注入的键（供 parity 断言） */
const injectedPerLang = {}

for (const lang of FILES) {
  const file = join(ROOT, `${lang}.json`)
  const doc = JSON.parse(readFileSync(file, 'utf-8'))

  // 深合并 MERGED
  const mergeInto = (src, dst) => {
    for (const [k, v] of Object.entries(src)) {
      if (v && typeof v === 'object' && !Array.isArray(v)) {
        if (typeof dst[k] !== 'object' || dst[k] === null) dst[k] = {}
        mergeInto(v, dst[k])
      } else {
        dst[k] = v
      }
    }
  }
  mergeInto(MERGED[lang], doc)
  mergeInto(NAMESPACES[lang], doc)

  writeFileSync(file, `${JSON.stringify(doc, null, 2)}\n`, 'utf-8')
  injectedPerLang[lang] = [...flatten(MERGED[lang]), ...flatten(NAMESPACES[lang])]
  console.log(`[v0330-i18n] ${lang}.json 注入 ${injectedPerLang[lang].length} 键`)
}

/* ---------- parity 自检（四语键集合必须完全一致） ---------- */
const base = injectedPerLang.zh
let failed = false
for (const lang of FILES.slice(1)) {
  const missing = base.filter((k) => !injectedPerLang[lang].includes(k))
  const extra = injectedPerLang[lang].filter((k) => !base.includes(k))
  if (missing.length || extra.length) {
    failed = true
    console.error(`[v0330-i18n] PARITY FAIL ${lang}: missing=${missing} extra=${extra}`)
  }
}
if (failed) process.exit(1)
console.log(`[v0330-i18n] 四语 parity OK（${base.length} 键 × ${FILES.length} 语）`)
