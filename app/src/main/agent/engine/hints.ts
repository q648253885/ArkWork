/* ============================================================
 * ArkWork — ReAct 运行期瞬时提示的通道标签（v0.31.0 D22）
 *
 * `pendingSystemHint` 是本引擎唯一的「瞬时提示」通道：reason-phase 在
 * 组装完历史消息后，把它作为**消息尾部的 user 角色消息**注入当轮请求，
 * 用完即清、不落 L1、不进对话 UI。
 *
 * 该通道承载两类语义完全不同的提示，注入时必须让模型能区分：
 *   1. 技能指令体 → `[Skill 指令]`：准则型长文本，模型要当作契约遵守；
 *   2. 引擎运行期提示 → `[引擎提示]`：工具达限 / 只读空转 / 清单未完成自愈 /
 *      图锚点等，是**引擎对自身内部状态的说明**，不是用户发言，也不是技能契约。
 *
 * 为什么必须显式标注（D22 缺陷教训）：
 *   通道此前对一切内容硬编码 `[Skill 指令]` 前缀。自救提示因此被模型读成
 *   「技能契约」，同时又被当作**用户的话**落进 L1（见 loop.ts 守卫）——
 *   标签与持久化两处都把它归错了类。标签在此单一来源，产出方自带、不靠调用方猜。
 * ============================================================ */

/** 技能指令体标签（skill 路径唯一；内容为准则型长文本） */
export const SKILL_HINT_LABEL = '[Skill 指令]'

/** 引擎运行期提示标签（工具达限 / 空转 / 清单未完成自愈 / 图锚点） */
export const ENGINE_HINT_LABEL = '[引擎提示]'

/** 引擎运行期提示的统一标注（产出方调用，避免手写前缀导致口径漂移） */
export function labelEngineHint(text: string): string {
  return `${ENGINE_HINT_LABEL}\n${text}`
}

/** 技能指令体的统一标注 */
export function labelSkillHint(text: string): string {
  return `${SKILL_HINT_LABEL}\n${text}`
}
