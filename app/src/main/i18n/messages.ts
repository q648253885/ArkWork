/** 语言归一化：未知值 → null（与 renderer i18n/index.ts 同规则） */
function normalizeLocale(v: unknown): Locale | null {
  return v === 'zh' || v === 'en' || v === 'ja' || v === 'ko' ? v : null
}

let cachedLocale: Locale | null = null

/**
 * 当前 UI 语言（同步接口：pushFaultCard / emitEvent 等调用点无法 await）。
 * 首次调用从 settings.json 同步读取一次并缓存；
 * 之后由 ipc/settings.ts 在写入 language 字段时经 setCachedUiLocale 同步缓存。
 */
export function getUiLocale(): Locale {
  if (cachedLocale) return cachedLocale
  try {
    const file = join(getArkworkDir(), 'settings.json')
    if (existsSync(file)) {
      const parsed = JSON.parse(readFileSync(file, 'utf-8')) as { language?: unknown }
      cachedLocale = normalizeLocale(parsed.language) ?? 'zh'
      return cachedLocale
    }
  } catch {
    /* fallthrough */
  }
  cachedLocale = 'zh'
  return cachedLocale
}

/** ipc/settings.ts 写入 language 后调用；非法值忽略 */
export function setCachedUiLocale(v: unknown): void {
  const l = normalizeLocale(v)
  if (l) cachedLocale = l
}

export type TParams = Record<string, string | number>

/**
 * 主进程文案取值：tFor(locale, key, params)
 * 缺失键回退 zh，再缺失返回 key 本身（便于发现漏配）。
 */
export function tFor(locale: Locale, key: string, params?: TParams): string {
  const table = MESSAGES[locale] ?? MESSAGES.zh
  let text = table[key] ?? MESSAGES.zh[key] ?? key
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      text = text.split(`{${k}}`).join(String(v))
    }
  }
  return text
}
